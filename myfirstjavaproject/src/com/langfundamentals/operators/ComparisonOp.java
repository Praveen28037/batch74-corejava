package com.langfundamentals.operators;


//4)Comparison operator : (== < > <= >= !=)
public class ComparisonOp {

	public static void main(String[] args) {
		
		int a=7;
		
		int b=5;
		
		System.out.println(a==b);//False
		
		System.out.println(a<b);//False
		
		System.out.println(a>b);//True
		
		System.out.println(a<=b);//False
		
		System.out.println(a>=b);//True
		
		System.out.println(a!=b);//True
	}

}
